import type { Metadata } from "next";
import { Caprasimo, Figtree, Zen_Maru_Gothic } from "next/font/google";
import "./globals.css";

export const metadata: Metadata = {
  title: "MotoCamp Pack",
  description: "Generated by create next app",
};
// フォントは CSS 変数（variable）として <html> に渡し、どの場面でどれを使うかは globals.css の @theme inline で決める

// 本文の英数字。--font-sans（body の既定）の1番目。日本語の文字は持たないので、日本語の部分は Zen Maru Gothic で表示される
const figtree = Figtree({
  subsets: ["latin"],
  variable: "--font-figtree",
});

// 日本語の文字全般（--font-sans の2番目）と、見出し h1〜h4（--font-heading の1番目。見出しは英数字もこのフォントになる）
// 日本語のサブセットは preload できないため preload: false（ブラウザが必要な文字の分だけ読み込む）
const zenMaruGothic = Zen_Maru_Gothic({
  weight: ["400", "500", "700"],
  preload: false,
  variable: "--font-zen-maru-gothic",
});

// ロゴなど、font-display クラスを付けた要素だけで使う（英字のみ。日本語の文字は持たない）
const caprasimo = Caprasimo({
  weight: "400",
  subsets: ["latin"],
  variable: "--font-caprasimo",
});

export default function RootLayout({ children }: LayoutProps<"/">) {
  return (
    <html
      lang="ja"
      className={`${figtree.variable} ${zenMaruGothic.variable} ${caprasimo.variable} h-full antialiased`}
    >
      <body className="min-h-full flex flex-col">{children}</body>
    </html>
  );
}
